/**
 * Offline check of the docs site (apps/docs-site): every slug in the Starlight
 * sidebar exists, every page on disk is reachable from it, and every internal
 * link and image points at something real. Astro's own build catches neither
 * broken links nor missing images, so this runs in CI on every PR.
 *
 *   pnpm docs:check
 */
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const app = join(import.meta.dirname, "..", "apps", "docs-site");
const root = join(app, "src", "content", "docs");
const publicDir = join(app, "public");
const problems: string[] = [];

// The sidebar is a literal in astro.config.mjs; reading the slugs out of it by
// pattern keeps this check free of an Astro import and its build pipeline.
const config = readFileSync(join(app, "astro.config.mjs"), "utf8");
const nav = new Set([...config.matchAll(/slug:\s*'([^']*)'/g)].map((m) => m[1]!));
const autogenerated = [...config.matchAll(/autogenerate:\s*\{\s*directory:\s*'([^']+)'/g)].map((m) => m[1]!);

const page = (p: string) =>
  [`${p}.mdx`, `${p}.md`, `${p}/index.mdx`, `${p}/index.md`]
    .map((f) => join(root, f))
    .find(existsSync);

for (const p of nav) {
  // The home page is the empty slug, which lives at index.mdx.
  if (!(p === "" ? existsSync(join(root, "index.mdx")) : page(p))) {
    problems.push(`the sidebar lists "${p}" but no such page exists`);
  }
}

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const full = join(dir, f);
    if (f === "node_modules" || f.startsWith(".")) return [];
    return statSync(full).isDirectory() ? files(full) : [full];
  });
}

const pages = files(root).filter((f) => /\.mdx?$/.test(f));
const reachable = new Set([...nav].map((p) => (p === "" ? join(root, "index.mdx") : page(p))));

for (const f of pages) {
  const rel = relative(root, f);
  const inAutogenerated = autogenerated.some((d) => rel.startsWith(`${d}/`));
  if (!reachable.has(f) && !inAutogenerated) {
    problems.push(`${rel} is in neither the sidebar nor an autogenerated directory`);
  }
  const text = readFileSync(f, "utf8").replace(/```[\s\S]*?```/g, "");
  const links = [...text.matchAll(/\]\((\/[^)\s#]*)[^)]*\)|(?:href|src)=["'](\/[^"'#]*)/g)].map(
    (m) => m[1] ?? m[2]!,
  );
  for (const link of links) {
    const target = link.replace(/\/$/, "");
    // Images and other files are served from public/ at the same path.
    const asset = join(publicDir, target);
    if (existsSync(asset) && statSync(asset).isFile()) continue;
    if (target === "" || page(target.slice(1))) continue;
    problems.push(`${rel} links to ${link}, which does not exist`);
  }
}

if (problems.length) {
  console.error(problems.map((p) => `✗ ${p}`).join("\n"));
  process.exit(1);
}
console.log(`docs ok: ${nav.size} slugs in the sidebar, ${pages.length} files checked`);
